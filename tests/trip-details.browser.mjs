// Run with the same isolated Playwright Core setup as planner.browser.mjs.
import assert from "node:assert/strict";
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || "playwright-core");
const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROME_EXECUTABLE || "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome" });
const base = process.env.QA_BASE_URL || "http://localhost:3200";
try {
  for (const width of [1440, 768, 390, 320]) {
    const context = await browser.newContext({ viewport: { width, height: 900 } });
    const page = await context.newPage();
    const errors = [];
    page.on("pageerror", (error) => errors.push(error.message));
    await page.goto(base + "/final-website");
    await page.getByRole("button", { name: /Try a three-day demo/ }).click();
    await page.getByLabel("Passport and travel documents", { exact: true }).check();
    await page.getByRole("tab").nth(2).click();
    const originalIds = await page.locator("[data-activity]").evaluateAll((els) => els.map((e) => e.dataset.activity));
    const edit = page.getByRole("button", { name: "Edit trip details", exact: true });
    const field = (name) => page.getByLabel(name, { exact: true });
    const save = () => page.getByRole("button", { name: "Save trip details", exact: true }).click();
    await edit.click();
    assert.equal(await field("Trip name").inputValue(), "A little mountain escape");
    assert.equal(await field("Start date").inputValue(), "2026-11-09");
    assert.equal(await field("End date").inputValue(), "2026-11-11");
    assert.equal(await field("Destination").inputValue(), "dolomites");
    assert.equal(await field("Travel pace").inputValue(), "Unhurried");
    assert.equal(await page.locator("dialog").evaluate((d) => d.scrollWidth <= d.clientWidth), true);
    await field("Trip name").fill("Discard this");
    await page.getByRole("button", { name: "Cancel", exact: true }).click();
    assert.equal(await page.locator("#workspace-title").innerText(), "A little mountain escape");
    assert.equal(await edit.evaluate((e) => e === document.activeElement), true);
    assert.equal(await page.getByRole("tab").nth(2).getAttribute("aria-selected"), "true");
    await edit.click();
    await field("Trip name").fill("");
    await save();
    assert.equal(await field("Trip name").getAttribute("aria-invalid"), "true");
    assert.equal(await field("Trip name").evaluate((e) => e === document.activeElement), true);
    await field("Trip name").fill("A Paris pause");
    await field("Destination").selectOption("paris");
    await field("Travel pace").selectOption("Balanced");
    await field("Start date").fill("2026-12-31");
    await field("End date").fill("2027-01-04");
    await save();
    assert.equal(await page.locator("#workspace-title").innerText(), "A Paris pause");
    assert.equal(await page.getByRole("tab").count(), 5);
    assert.equal(await page.getByRole("tab").nth(2).getAttribute("aria-selected"), "true");
    assert.deepEqual(await page.locator("[data-activity]").evaluateAll((els) => els.map((e) => e.dataset.activity)), originalIds);
    assert.equal(await field("Passport and travel documents").isChecked(), true);
    assert.match(await page.getByRole("status").innerText(), /Review your activities/);
    assert.match(await page.getByTestId("budget-spent").innerText(), /\$115.00[\s\S]*\$450.00/);
    assert.equal(await page.getByRole("img", { name: "The River Seine and the historic buildings of Paris", exact: true }).count(), 1);
    await page.getByRole("tab").nth(4).click();
    assert.equal(await page.locator("[data-activity]").count(), 0);
    await page.getByRole("tab").nth(2).click();
    await edit.click();
    await field("End date").fill("2026-12-31");
    await save();
    assert.match(await page.getByRole("dialog").innerText(), /4 days and 4 activities/);
    assert.equal(await page.getByRole("button", { name: "Keep all days", exact: true }).evaluate((e) => e === document.activeElement), true);
    await page.getByRole("button", { name: "Keep all days", exact: true }).click();
    assert.equal(await field("End date").inputValue(), "2026-12-31");
    await page.keyboard.press("Escape");
    assert.equal(await page.getByRole("tab").count(), 5);
    assert.equal(await page.getByRole("tab").nth(2).getAttribute("aria-selected"), "true");
    assert.deepEqual(await page.locator("[data-activity]").evaluateAll((els) => els.map((e) => e.dataset.activity)), originalIds);
    await edit.click();
    await field("End date").fill("2026-12-31");
    await save();
    await page.keyboard.press("Escape");
    assert.equal(await page.getByRole("tab").count(), 5);
    assert.equal(await page.getByRole("tab").nth(2).getAttribute("aria-selected"), "true");
    assert.deepEqual(await page.locator("[data-activity]").evaluateAll((els) => els.map((e) => e.dataset.activity)), originalIds);
    await edit.click();
    await field("End date").fill("2026-12-31");
    await save();
    await page.getByRole("button", { name: "Shorten trip", exact: true }).click();
    assert.equal(await page.getByRole("tab").count(), 1);
    assert.equal(await page.getByRole("tab").first().getAttribute("aria-selected"), "true");
    assert.equal(await field("Passport and travel documents").isChecked(), true);
    assert.match(await page.getByTestId("budget-spent").innerText(), /\$28.00[\s\S]*\$450.00/);
    // Extending then removing empty days needs no destructive confirmation.
    await edit.click();
    await field("End date").fill("2027-01-02");
    await save();
    await page.getByRole("tab").nth(2).click();
    await edit.click();
    await field("End date").fill("2026-12-31");
    await save();
    assert.equal(await page.getByRole("dialog").count(), 0);
    assert.equal(await page.getByRole("tab").first().getAttribute("aria-selected"), "true");
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.getByRole("navigation", { name: "Main navigation" }).getByRole("button", { name: /Demo trips/ }).click();
    assert.equal(await page.getByRole("heading", { name: "A Paris pause", exact: true }).count(), 1);
    await page.getByRole("button", { name: /Open demo/ }).click();
    await page.reload();
    await page.getByRole("button", { name: /Try a three-day demo/ }).click();
    assert.equal(await page.locator("#workspace-title").innerText(), "A little mountain escape");
    assert.equal(await page.getByRole("tab").count(), 3);
    assert.deepEqual(errors, []);
    console.log(`PASS trip details ${width}: prefill, cancel, validation, shift, extend, destination, shortening, selection, refresh`);
    await context.close();
  }
} finally {
  await browser.close();
}
